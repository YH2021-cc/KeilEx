function resolveLanguage(setting, vscodeLanguage) {
  if (setting === 'zh') return 'zh';
  if (setting === 'en') return 'en';
  return String(vscodeLanguage || '').toLowerCase().startsWith('zh') ? 'zh' : 'en';
}

function t(language, key, ...args) {
  const dict = STRINGS[language] || STRINGS.zh;
  let text = dict[key] || STRINGS.zh[key] || key;
  args.forEach((arg, index) => {
    text = text.replace(new RegExp(`\\{${index}\\}`, 'g'), String(arg));
  });
  return text;
}

function strings(language) {
  return { ...(STRINGS[language] || STRINGS.zh) };
}

module.exports = { STRINGS, resolveLanguage, t, strings };
